#!/usr/bin/env python3
"""Canadian Winter -- procedural project icon (polish 5 §1).

Writes ``icon.svg`` at the project root, the file ``application/config/icon`` in
project.godot points at (the window icon, the editor's project list). The
original logo was lost when the project folder was moved and was never in git,
so this draws a new one from code: a snowed-in house at dusk with one warm
window, in the game's own palette (scripts/ui/ui_kit.gd: the navy panels, the
orange ACCENT, the off-white TEXT; the dusk blue of the default clear colour).

The shapes are few and large so the mark still reads at 16 px: a white roof of
snow over a dark house, an orange window and a white snowbank, on a rounded
navy tile. The output is plain SVG text, deterministic, with no raster data.

Usage (from the project root):
    python3 tools/icon/gen_icon.py            # writes icon.svg
    python3 tools/icon/gen_icon.py OUT.svg    # writes somewhere else
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SIZE = 256          # viewBox and nominal size; Godot rasterizes the SVG at any scale
RADIUS = 52         # tile corner radius

# The game's palette (ui_kit.gd and project.godot), as hex.
NIGHT = "#141a38"       # top of the sky: UIKit BG navy, a little bluer
DUSK = "#5a6496"        # bottom of the sky: the default clear colour, darker
HOUSE = "#0e1328"       # house silhouette: darker than any sky
SNOW = "#f2f3f8"        # UIKit TEXT
SNOW_SHADE = "#c3cce4"  # the snow's shadowed side
WINDOW = "#fa8c2e"      # UIKit ACCENT
WINDOW_GLOW = "#ffd08a"  # lamp-lit centre of the window
MULLION = "#b8581c"     # window frame: a darker orange, so the window stays orange at 16 px


def _pts(points: list[tuple[float, float]]) -> str:
    return " ".join("%g,%g" % p for p in points)


def build() -> str:
    s = SIZE
    parts: list[str] = []
    add = parts.append
    add('<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">' % (s, s, s, s))
    add("<!-- Generated by tools/icon/gen_icon.py: edit the generator, not this file. -->")
    add("<defs>")
    add('<linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">'
        '<stop offset="0" stop-color="%s"/><stop offset="1" stop-color="%s"/></linearGradient>' % (NIGHT, DUSK))
    add('<radialGradient id="lamp" cx="0.5" cy="0.55" r="0.6">'
        '<stop offset="0" stop-color="%s"/><stop offset="1" stop-color="%s"/></radialGradient>' % (WINDOW_GLOW, WINDOW))
    add('<clipPath id="tile"><rect width="%d" height="%d" rx="%d" ry="%d"/></clipPath>' % (s, s, RADIUS, RADIUS))
    add("</defs>")
    add('<g clip-path="url(#tile)">')
    # Sky.
    add('<rect width="%d" height="%d" fill="url(#sky)"/>' % (s, s))
    # A few falling flakes: detail for the large sizes, below a pixel at 16 px.
    for x, y, r in [(46, 52, 6), (92, 30, 4), (198, 40, 5), (226, 92, 4), (30, 108, 4), (166, 22, 3)]:
        add('<circle cx="%d" cy="%d" r="%d" fill="%s" fill-opacity="0.85"/>' % (x, y, r, SNOW))
    # The house: chimney, roof and walls as one dark silhouette.
    add('<rect x="158" y="70" width="22" height="50" fill="%s"/>' % HOUSE)
    add('<polygon points="%s" fill="%s"/>' % (_pts([(50, 140), (128, 70), (206, 140)]), HOUSE))
    add('<rect x="72" y="130" width="112" height="90" fill="%s"/>' % HOUSE)
    # Snow on the chimney and a thick roof of snow with rounded eaves.
    add('<rect x="154" y="60" width="30" height="14" rx="7" fill="%s"/>' % SNOW)
    add('<path d="M 34 146 L 128 58 L 222 146 Q 224 160 210 158 L 128 86 L 46 158 Q 32 160 34 146 Z" fill="%s"/>' % SNOW)
    # The window: one warm square with a mullion cross.
    add('<rect x="104" y="138" width="48" height="46" rx="4" fill="url(#lamp)"/>')
    add('<rect x="126.5" y="138" width="3" height="46" fill="%s"/>' % MULLION)
    add('<rect x="104" y="159.5" width="48" height="3" fill="%s"/>' % MULLION)
    # The snowbank in front, with a shaded lower drift.
    add('<path d="M 0 196 C 44 178 92 204 140 194 C 182 186 218 174 256 186 L 256 256 L 0 256 Z" fill="%s"/>' % SNOW)
    add('<path d="M 0 226 C 60 212 120 236 180 224 C 210 218 236 214 256 218 L 256 256 L 0 256 Z" fill="%s"/>' % SNOW_SHADE)
    add("</g>")
    add("</svg>")
    return "\n".join(parts) + "\n"


def main(argv: list[str]) -> int:
    out = Path(argv[1]) if len(argv) > 1 else ROOT / "icon.svg"
    out.write_text(build(), encoding="utf-8")
    print("wrote %s" % out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
